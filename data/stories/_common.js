// ケーススタディ（ストーリー問題）の共通定義：資料の種類と「判断したいこと × 資料」の対応表。
// 各ストーリーは data/stories/story-S*.js で window.STORIES に登録する。書き方は docs/CONTENT_GUIDE.md の「7. ケーススタディ」。
(function () {
  const T = String.raw;
  const root = typeof window !== 'undefined' ? window : globalThis;
  const MoT = (root.MoT = root.MoT || {});
  root.STORIES = root.STORIES || [];

  // 「どの資料を開くか」問題の選択肢。key はストーリーの pick.answer・uses で使う。
  MoT.SOURCES = [
    { key: 'PL', name: '損益計算書（PL）', what: '1年間でいくら稼いだか（売上・費用・利益）' },
    { key: 'BS', name: '貸借対照表（BS）', what: '期末の時点で何を持ち、そのお金をどう調達したか' },
    { key: 'CF', name: 'キャッシュ・フロー計算書（CF）', what: '1年間の現金の出入り（営業・投資・財務）' },
    { key: 'SEG', name: 'セグメント情報（注記）', what: '事業別・地域別の売上・利益・資産' },
    { key: 'MKT', name: '株価・市場データ', what: '時価総額、金利、β、投資家の期待' },
    { key: 'PLAN', name: '事業計画・将来予測', what: 'これから先の売上・CFの見通し（社内資料・会社予想）' },
  ];

  // ケーススタディの背骨：判断したいこと → 主に見る資料 → 使う指標
  MoT.STORY_MATRIX = T`
| 判断したいこと | 主に見る資料 | 使う指標（つながる用語） |
|---|---|---|
| 本業で稼ぐ力はあるか | PL | 営業利益率、EBITDA（A3） |
| 投じた資本を効率よく使えているか | PL＋BS | ROIC分解（B2）、ROE分解（B1） |
| 現金は回っているか、倒産しないか | CF＋BS | FCF（A5）、運転資本（A2）、自己資本比率 |
| 大きな投資に耐えられるか、どう調達するか | CF＋BS | 営業CF、設備投資と減価償却（A1）、有利子負債 |
| どの事業に資源を振り向けるか | セグメント情報 | 事業別の利益率・ROIC、PPM（F1） |
| 投資家からどう評価されているか | 株価＋BS・PL | PBR＝ROE×PER（D4）、資本コスト（C1） |
| この投資・事業を実行すべきか | 事業計画＋資本コスト | NPV（E1）、IRR（E2）、リアルオプション（E3） |`;

  MoT.STORY_LEAD = T`実際の企業の出来事を題材に、「何を判断したいから、どの資料を開くか」を体験する問題。場面ごとに **資料を選ぶ → 数字を読む・計算する → 判断する** の順で進む。最後に、何が起きたかと、どの資料に兆しが出ていたかを振り返る。

> 数値は会社の公表資料（有価証券報告書・決算短信・アニュアルレポート）から取り、億円単位に丸めている。教材用の仮定を置いたところは、その場面で「仮定」と明記している。`;
})();
